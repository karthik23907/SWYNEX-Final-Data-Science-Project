"""Generate reports/data_quality_report.md and figures from the real pipeline output.

Usage: python -m src.report
"""
from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from src import data_prep as dp

REPORT_DIR = dp.ROOT / "reports"
FIG_DIR = REPORT_DIR / "figures"
PALETTE = {"No": "#4C78A8", "Yes": "#E45756"}


def _style() -> None:
    plt.rcParams.update({
        "figure.dpi": 130, "axes.spines.top": False, "axes.spines.right": False,
        "axes.grid": True, "grid.alpha": 0.25, "font.size": 10,
    })


def make_figures(df: pd.DataFrame) -> list[str]:
    _style()
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    label = df["churn"].map({0: "No", 1: "Yes"})
    files = []

    # 1. Churn rate by contract
    rate = df.groupby("contract", observed=True)["churn"].mean().mul(100)
    fig, ax = plt.subplots(figsize=(6, 3.6))
    bars = ax.bar(rate.index.astype(str), rate.values, color="#4C78A8")
    ax.bar_label(bars, fmt="%.1f%%", padding=3)
    ax.set(ylabel="Churn rate (%)", title="Churn rate by contract type", ylim=(0, rate.max() * 1.2))
    ax.grid(axis="x", visible=False)
    fig.tight_layout(); fig.savefig(FIG_DIR / "churn_by_contract.png"); plt.close(fig)
    files.append("churn_by_contract.png")

    # 2. Monthly charges by churn
    fig, ax = plt.subplots(figsize=(6, 3.6))
    for k in ("No", "Yes"):
        ax.hist(df.loc[label == k, "monthly_charges"], bins=30, alpha=0.65, label=f"Churn = {k}", color=PALETTE[k])
    ax.set(xlabel="Monthly charges", ylabel="Customers", title="Monthly charges by churn status")
    ax.legend(frameon=False)
    fig.tight_layout(); fig.savefig(FIG_DIR / "monthly_charges_by_churn.png"); plt.close(fig)
    files.append("monthly_charges_by_churn.png")

    # 3. Tenure distribution
    fig, ax = plt.subplots(figsize=(6, 3.6))
    ax.hist(df["tenure"], bins=36, color="#4C78A8")
    ax.set(xlabel="Tenure (months)", ylabel="Customers", title="Customer tenure distribution")
    fig.tight_layout(); fig.savefig(FIG_DIR / "tenure_distribution.png"); plt.close(fig)
    files.append("tenure_distribution.png")
    return files


def iqr_outliers(s: pd.Series) -> tuple[int, float, float]:
    q1, q3 = s.quantile([0.25, 0.75])
    lo, hi = q1 - 1.5 * (q3 - q1), q3 + 1.5 * (q3 - q1)
    return int(((s < lo) | (s > hi)).sum()), lo, hi


def build_report() -> str:
    raw = dp.load_raw()
    df, audit = dp.clean(raw)
    checks = dp.validate(df)
    figs = make_figures(df)

    raw_mem, clean_mem = raw.memory_usage(deep=True).sum() / 1e6, df.memory_usage(deep=True).sum() / 1e6
    blanks = int(raw["TotalCharges"].str.strip().eq("").sum())
    obj_before = sum(not pd.api.types.is_numeric_dtype(raw[c]) for c in raw.columns)
    num_after = sum(pd.api.types.is_numeric_dtype(df[c]) for c in df.columns)

    # Evidence for the imputation decision
    blank_rows = raw[raw["TotalCharges"].str.strip().eq("")]
    expected = df["tenure"] * df["monthly_charges"]
    mask = expected > 0
    dev = ((df["total_charges"] - expected)[mask].abs() / expected[mask])
    large_dev = int((dev > 0.30).sum())

    avg_total = df.loc[df["tenure"] > 0, "total_charges"].mean()

    L = []
    L += ["# Data Quality Report: Telco Customer Churn", "",
          "_Auto-generated by `python -m src.report`; numbers come from the pipeline run, not hand-typed._", ""]
    L += ["## 1. Summary", "",
          "| Metric | Raw | Clean |", "|---|---:|---:|",
          f"| Rows | {len(raw):,} | {len(df):,} |",
          f"| Columns | {raw.shape[1]} | {df.shape[1]} |",
          f"| Missing cells (true NaN) | {int(raw.isna().sum().sum())} | {int(df.isna().sum().sum())} |",
          f"| Hidden blanks (empty strings) | {blanks} | 0 |",
          f"| Non-numeric (text) columns | {obj_before} | {df.shape[1] - num_after} (typed categories/ids) |",
          f"| Memory (MB) | {raw_mem:.2f} | {clean_mem:.2f} |", ""]
    L += ["## 2. The key finding: hidden missing values", "",
          f"`pd.isna()` reports **0** missing cells in the raw file, but `TotalCharges` contains **{blanks} blank strings**. "
          "This also forces the whole column to text, which silently breaks any numeric analysis.", "",
          f"All {blanks} affected customers have `tenure = 0` "
          f"(tenure values: {[int(t) for t in sorted(blank_rows['tenure'].unique())]}), i.e. they signed up this period and have not been billed yet. "
          f"Their churn label is {', '.join(sorted(blank_rows['Churn'].unique()))} in every case.", "",
          f"- **Decision:** the true value is 0, so impute `0.0` rather than the mean/median, which would invent about "
          f"${avg_total:,.0f} of revenue per customer who has paid nothing.",
          "- **Safeguard:** the pipeline raises an error if a blank ever appears for a customer with `tenure > 0`.", ""]
    L += ["## 3. Cleaning log", "", "| # | Step | What & why | Rows affected |", "|---|---|---|---:|"]
    for i, s in enumerate(audit.steps, 1):
        L.append(f"| {i} | {s['step']} | {s['detail']} | {s['rows_affected']:,} |")
    L += ["", "## 4. Validation checks", "", "| Check | Result | Detail |", "|---|:-:|---|"]
    for name, ok, detail in checks:
        L.append(f"| {name} | {'PASS' if ok else 'FAIL'} | {detail} |")
    L += ["", "## 5. Outliers (IQR rule), reviewed and kept", "",
          "| Column | Outliers | Fence (low, high) |", "|---|---:|---|"]
    for c in ["tenure", "monthly_charges", "total_charges"]:
        n, lo, hi = iqr_outliers(df[c])
        L.append(f"| {c} | {n} | ({lo:.1f}, {hi:.1f}) |")
    total_out = sum(iqr_outliers(df[c])[0] for c in ["tenure", "monthly_charges", "total_charges"])
    L += ["", f"{total_out} IQR outliers were found, so no rows were removed or capped. "
          "`total_charges` is naturally right-skewed because long-tenure customers accumulate more charges; "
          "consider a log transform for linear models downstream.", ""]
    L += ["## 6. Consistency observation (not altered)", "",
          f"`total_charges` should be close to `tenure x monthly_charges`. {large_dev:,} rows "
          f"({large_dev / mask.sum():.1%}) deviate by more than 30%; a plausible cause is plan changes over a "
          "customer's lifetime, but this cannot be verified from the dataset. Values were left untouched and are flagged for downstream awareness.", ""]
    rate = df["churn"].mean()
    L += ["## 7. Target balance", "",
          f"Churn = Yes for **{rate:.1%}** of customers ({int(df['churn'].sum()):,} of {len(df):,}). "
          "The classes are moderately imbalanced: use stratified splits and report precision/recall/PR-AUC, not accuracy alone.", ""]
    L += ["## 8. Figures", ""]
    L += [f"![{f}](figures/{f})" for f in figs]
    L.append("")
    return "\n".join(L)


if __name__ == "__main__":
    REPORT_DIR.mkdir(exist_ok=True)
    (REPORT_DIR / "data_quality_report.md").write_text(build_report(), encoding="utf-8")
    print("Wrote reports/data_quality_report.md")
